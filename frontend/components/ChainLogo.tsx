export function ChainLogo({ chain, size = 34 }: { chain: string; size?: number }) {
  const normalized = chain.toUpperCase();
  const matchedKey =
    normalized === "TRON"
      ? "TRON"
      : normalized === "ETHEREUM" || normalized === "ETH"
      ? "Ethereum"
      : normalized === "BSC" || normalized === "BNB" || normalized === "BNB CHAIN"
      ? "BNB Chain"
      : normalized === "POLYGON" || normalized === "MATIC" || normalized === "POL"
      ? "Polygon"
      : normalized === "BITCOIN" || normalized === "BTC"
      ? "Bitcoin"
      : normalized === "SOLANA" || normalized === "SOL"
      ? "Solana"
      : chain;

  const glyph = glyphs[matchedKey] || glyphs[chain];
  if (!glyph) {
    return (
      <span
        className="chain-logo"
        style={{ width: size, height: size, background: "#4A5568", color: "#FFF", display: "grid", placeItems: "center", fontSize: size * 0.35, fontWeight: 800 }}
      >
        {chain.slice(0, 3).toUpperCase()}
      </span>
    );
  }

  return (
    <span className="chain-logo" style={{ width: size, height: size, background: glyph.bg }} aria-hidden="true">
      <svg viewBox={glyph.viewBox} width={size} height={size} focusable="false">
        {glyph.children}
      </svg>
    </span>
  );
}
